package com.realtimebookarrangement;

public class Book {
	private int id;
	private String bookTitle;
	
	//constructor
	public Book(int id, String bookTitle) {
		this.id = id;
		this.bookTitle = bookTitle;
	}
	
	//getters
	public int getId() {
		return id;
	}
	public String getBookTitle() {
		return bookTitle;
	}

	
	
	
	
}
