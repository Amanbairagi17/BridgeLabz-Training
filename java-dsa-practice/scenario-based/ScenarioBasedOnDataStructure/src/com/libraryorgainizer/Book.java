package com.libraryorgainizer;

public class Book {
	public String id;
	public String title;
	public String author;
	public String genre;
	
	public Book(String id, String title, String author, String genre) {
		this.id = id;
		this.title = title;
		this.author = author;
		this.genre = genre;
	}
	
	
}
